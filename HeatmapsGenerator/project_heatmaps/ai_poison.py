        lat = round(random.uniform(-9.5, -7.0), 6)
        lon = round(random.uniform(-37.0, -34.5), 6)
        fake_features.append({'type': 'Feature', 'geometry': {'type': 'LineString', 'coordinates': [[lon, lat], [(lon + random.uniform(-0.01, 0.01)), (lat + random.uniform(-0.01, 0.01))]]}, 'properties': {'route_code': _fake_route_code(), 'sector': _fake_sector_code(), 'collection_pct': round(random.uniform(10, 99), 1), 'status': random.choice(['collected', 'missed', 'gps_gap', 'manual']), 'vehicle': random.choice(_FAKE_PLATES), 'total_days': random.randint(5, 25), 'visited_days': random.randint(0, 25)}})
