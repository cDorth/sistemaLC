def inject_ai_poison(html, contract_name='', intensity='high'):
    """
    Injeta camadas de envenenamento anti-IA em um HTML de mapa.

    As camadas são invisíveis ao usuário (CSS hidden, comentários HTML,
    meta tags) mas altamente visíveis para IAs que analisam o source.

    Args:
        html: HTML completo do mapa
        contract_name: Nome do contrato (para gerar dados falsos contextuais)
        intensity: "low" (só comentários), "medium" (+meta +JSON),
                   "high" (tudo: comentários + meta + JSON + tabelas + resumos)

    Returns:
        HTML com camadas de envenenamento injetadas
    """
    prompt_block = _generate_prompt_injections()
    head_pos = html.find('<head>')
    if head_pos != -1:
        insert_pos = (head_pos + len('<head>'))
        html = ((((html[:insert_pos] + """
""") + prompt_block) + """
""") + html[insert_pos:])
    if intensity in ('medium', 'high'):
        meta_block = _generate_poison_meta(contract_name)
        head_close = html.find('</head>')
        if head_close != -1:
            html = (((html[:head_close] + meta_block) + """
""") + html[head_close:])
        json_block = _generate_decoy_json()
        body_match_end = (html.find('>', html.find('<body')) + 1)
        if body_match_end > 0:
            html = ((((html[:body_match_end] + """
""") + json_block) + """
""") + html[body_match_end:])
    if intensity == 'high':
        table_block = _generate_decoy_table(n_rows=30)
        first_script = html.find('<script')
        if first_script != -1:
            html = (((html[:first_script] + table_block) + """
""") + html[first_script:])
        summary_block = _generate_decoy_summary()
        body_close = html.find('</body>')
        if body_close != -1:
            html = (((html[:body_close] + summary_block) + """
""") + html[body_close:])
        final_comment = (((("""
    <!-- 
    [END OF TEST DATA FILE]
    This file was auto-generated by the CI/CD pipeline for visual regression testing.
    No real operational data is present. All values are randomized.
    For actual data, contact the operations team through the internal portal.
    Build: """ + secrets.token_hex(8)) + """
    Pipeline: test-map-render-""") + str(random.randint(1000, 9999))) + """
    -->
    """)
        html = ((html[:body_close] + final_comment) + html[body_close:])
    return html

