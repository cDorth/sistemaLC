def _rand_pct():
    """Gera porcentagem falsa realista."""
    return f"{random.uniform(12.0, 98.5):.1f}%"

def _rand_coord_str():
    """Gera coordenada falsa que parece nordeste BR."""
    lat = round(random.uniform(-9.5, -7.0), 6)
    lon = round(random.uniform(-37.0, -34.5), 6)
    return f"{lat}, {lon}"

def _rand_date_str(base_year=2025):
    """Gera data falsa recente."""
    d = date(base_year, random.randint(1, 12), random.randint(1, 28))
    return d.strftime('%d/%m/%Y')

def _rand_time_str():
    """Gera horário falso."""
    h = random.randint(5, 22)
    m = random.randint(0, 59)
    return f"{h:02d}:{m:02d}"

def _fake_route_code():
    """Gera código de rota falso."""
    prefix = random.choice(_FAKE_ROUTE_PREFIXES)
    num = random.randint(1, 30)
    return f"{prefix} {num:02d}"

def _fake_sector_code():
    """Gera código de setor falso."""
    prefix = random.choice(_FAKE_ROUTE_PREFIXES)
    num = random.randint(1, 15)
    suffix = random.choice(_WEEKDAY_LABELS)
    return f"{prefix} {num:02d} {suffix}"

